def business_days(start: datetime, end: datetime) -> list[datetime]:
    day = start
    days = []
    while day <= end:
        if day.weekday() < 5:
            days.append(day)
        day += timedelta(days=1)
    return days


def make() -> None:
    rng = random.Random(SEED)
    names = list(zip(rng.sample(FIRST_NAMES, 8), rng.sample(LAST_NAMES, 8), strict=True))
    codes = rng.sample(range(1000, 10000), 8)

    slots = []
    for day in business_days(datetime(2026, 11, 5, tzinfo=CENTRAL), datetime(2026, 11, 18, tzinfo=CENTRAL)):
        for hour, minute in SLOT_TIMES:
            start = day.replace(hour=hour, minute=minute)
            slots.append(
                {
                    "id": f"S{start:%m%d}-{start:%H%M}",
                    "start": start.isoformat(),
                    "duration_min": 30,
                    "interviewer": rng.choice(INTERVIEWERS),
                    "status": "open",
                    "held_by": None,
                }
            )

    candidates = []
    invite_base = datetime(2026, 10, 28, 9, 0, tzinfo=CENTRAL)
    for (first, last), code, stage in zip(names, codes, STAGES, strict=True):
        invited_at = invite_base + timedelta(hours=rng.randint(0, 96), minutes=rng.choice([0, 10, 25, 40]))
        booked_slot = None
        if stage in ("booked", "moved_once"):
            slot = rng.choice([s for s in slots if s["status"] == "open" and s["start"] > "2026-11-05"])
            slot["status"], slot["held_by"] = "booked", f"ACME-{code}"
            booked_slot = slot["id"]
        candidates.append(
            {
                "code": f"ACME-{code}",
                "pin": f"{rng.randint(0, 9999):04d}",
                "name": f"{first} {last}",
                "role": rng.choice(ROLES),
                "stage": stage,
                "invited_at": invited_at.isoformat(),
                "booked_slot": booked_slot,
                "moves_used": 1 if stage == "moved_once" else 0,
                "callback_requested": False,
            }
        )

    baseline = []
    for i in range(40):
        invited = datetime(2026, 6, 1, 9, 0, tzinfo=CENTRAL) + timedelta(hours=rng.randint(0, 24 * 120))
        booked = None
        if rng.random() < 0.85:
            hours = round(rng.lognormvariate(3.4, 0.7), 1)  # median about 30 hours, a long tail
            booked = invited + timedelta(hours=hours)
        baseline.append(
            {
                "invite_id": f"B{i + 1:03d}",
                "invited_at": invited.isoformat(),
                "booked_at": booked.isoformat() if booked else "",
                "hours_to_book": f"{(booked - invited).total_seconds() / 3600:.1f}" if booked else "",
                "channel": "phone" if rng.random() < 0.3 else "email",
                "synthetic": "true",
            }
        )

    DATA.mkdir(exist_ok=True)
    (DATA / "candidates.yaml").write_text(
        HEADER
        + yaml.safe_dump({"synthetic": True, "firm": "ACME", "candidates": candidates}, sort_keys=False)
    )
    (DATA / "slots.yaml").write_text(
        HEADER
        + yaml.safe_dump({"synthetic": True, "timezone": "America/Chicago", "slots": slots}, sort_keys=False)
    )
    with (DATA / "baseline_invites.csv").open("w", newline="") as f:
        f.write(HEADER)
        writer = csv.DictWriter(f, fieldnames=list(baseline[0]))
        writer.writeheader()
        writer.writerows(baseline)
    print(
        f"wrote {len(candidates)} candidates, {len(slots)} slots, {len(baseline)} baseline invites to {DATA}"
    )
    make_outbound({c["code"] for c in candidates})


def make_outbound(taken_codes: set[str]) -> None:
    """data/roles.yaml (the posted questions and the recruiters' interview slots), data/applications.yaml and
    data/baseline_screens.csv, from their own seed (DR-025, card 08)."""
    rng = random.Random(OUTBOUND_SEED)
    interview_slots = []
    for day in business_days(datetime(2026, 11, 5, tzinfo=CENTRAL), datetime(2026, 11, 18, tzinfo=CENTRAL)):
        for (hour, minute), recruiter in INTERVIEW_TIMES:
            start = day.replace(hour=hour, minute=minute)
            interview_slots.append(
                {
                    "id": f"S{start:%m%d}-{start:%H%M}",
                    "start": start.isoformat(),
                    "duration_min": 20,
                    "recruiter": recruiter,
                    "status": "open",
                    "held_by": None,
                }
            )

    codes = [c for c in rng.sample(range(1000, 10000), 20) if f"ACME-{c}" not in taken_codes][
        : len(APPLICANT_ROLES)
    ]
    names = rng.sample(APPLICANT_FIRST_NAMES, len(APPLICANT_ROLES))
    applied_base = datetime(2026, 11, 4, 8, 0, tzinfo=CENTRAL)
    applications = []
    for code, name, role, zone, consented in zip(
        codes, names, APPLICANT_ROLES, APPLICANT_ZONES, APPLICANT_CONSENT, strict=True
    ):
        applied = applied_base + timedelta(hours=rng.randint(0, 9), minutes=rng.choice([0, 5, 20, 35, 50]))
        applications.append(
            {
                "code": f"ACME-{code}",
                "first_name": name,
                "role": role,
                "zone": zone,
                "pin": f"{rng.randint(0, 9999):04d}",
                "applied_at": applied.isoformat(),
                "consent": {
                    "version": CONSENT_VERSION,
                    "accepted": consented,
                    "at": (applied - timedelta(seconds=rng.randint(15, 90))).isoformat(),
                    "source": "careers-form",
                },
            }
        )

    screens = []
    for i in range(40):
        # A recruiter's phone screen in office hours, 09:00 to 17:45 Central, on any of 90 days.
        screened = datetime(2026, 7, 1, 9, 0, tzinfo=CENTRAL) + timedelta(
            days=rng.randint(0, 90), hours=rng.randint(0, 8), minutes=rng.choice([0, 15, 30, 45])
        )
        minutes = round(rng.lognormvariate(math.log(18), 0.35), 1)  # median about 18 minutes a screen
        screens.append(
            {
                "screen_id": f"P{i + 1:03d}",
                "screened_at": screened.isoformat(),
                "role": rng.choice(APPLICANT_ROLES),
                "minutes": f"{minutes:.1f}",
                "attempts_to_reach": str(rng.choice([1, 1, 1, 2, 2, 3])),
                "synthetic": "true",
            }
        )

    (DATA / "roles.yaml").write_text(
        OUTBOUND_HEADER
        + yaml.safe_dump(
            {"synthetic": True, "firm": "ACME", "roles": ROLES_SPEC, "interview_slots": interview_slots},
            sort_keys=False,
            width=120,
        )
    )
    (DATA / "applications.yaml").write_text(
        OUTBOUND_HEADER
        + yaml.safe_dump(
            {
                "synthetic": True,
                "firm": "ACME",
                "consent_texts": {CONSENT_VERSION: CONSENT_TEXT},
                "applications": applications,
            },
            sort_keys=False,
            width=120,
        )
    )
    with (DATA / "baseline_screens.csv").open("w", newline="") as f:
        f.write(OUTBOUND_HEADER)
        writer = csv.DictWriter(f, fieldnames=list(screens[0]))
        writer.writeheader()
        writer.writerows(screens)
    print(
        f"wrote {len(ROLES_SPEC)} roles, {len(interview_slots)} interview slots, {len(applications)} applications, "
        f"{len(screens)} baseline screens to {DATA}"
    )


if __name__ == "__main__":
    make()
